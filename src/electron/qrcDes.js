const BITOF = n => (1 << n) >>> 0;

const DES_BITMAP = Array.from({ length: 64 }, (_, i) => BITOF(31 - (i % 32)));

const DES_ROTATION_MASK = [0, 0x80000000, 0xc0000000];

export const DesType = { Encode: 0, Decode: 1 };

// 16 个子密钥
const subKeys = [];
const tempKey = { low: 0, high: 0 };

const uint32 = v => v >>> 0;

function createSubKey(index) {
  const sub = subKeys[index];
  const rcnt = DES_ROTATIONS[index];
  let v6 = tempKey.low & DES_ROTATION_MASK[rcnt];
  let v7 = tempKey.high & DES_ROTATION_MASK[rcnt];
  if (rcnt === 1) {
    v6 = v6 >>> 27;
    v7 = v7 >>> 27;
  } else {
    v6 = v6 >>> 26;
    v7 = v7 >>> 26;
  }
  tempKey.low = uint32(tempKey.low << rcnt) & MASK32;
  tempKey.high = uint32(tempKey.high << rcnt) & MASK32;
  tempKey.low = uint32(tempKey.low | uint32(v6 & 0xfffffff0));
  tempKey.high = uint32(tempKey.high | uint32(v7 & 0xfffffff0));
  for (let i = 0; i < 48; ++i) {
    const v10 = DES_PERMUTED[i];
    if (i >= 24) {
      if (DES_BITMAP[v10 - 29 + 1] & tempKey.high)
        sub.high = uint32(sub.high | DES_BITMAP[i - 24]);
    } else if (tempKey.low & DES_BITMAP[v10 - 1]) {
      sub.low = uint32(sub.low | DES_BITMAP[i]);
    }
  }
}

function makeFirstKey(key) {
  const first = { low: key.readUInt32LE(0), high: key.readUInt32LE(4) };
  tempKey.high = tempKey.low = 0;
  if (!subKeys.length) {
    for (let i = 0; i < 16; ++i) subKeys.push({ low: 0, high: 0 });
  } else {
    subKeys.forEach(k => (k.high = k.low = 0));
  }
  // 把 key 转置压缩为 56 位
  for (let i = 0; i < 28; ++i) {
    let item = DES_TRANSFORM[i];
    // 置换映射表从 1 开始，这里 -1
    let got = (item <= 32 ? first.low : first.high) & DES_BITMAP[item - 1];
    if (got) tempKey.low = uint32(tempKey.low | DES_BITMAP[i]);
    item = DES_TRANSFORM[i + 28];
    got = (item <= 32 ? first.low : first.high) & DES_BITMAP[item - 1];
    if (got) tempKey.high = uint32(tempKey.high | DES_BITMAP[i]);
  }
  for (let i = 0; i < 16; ++i) createSubKey(i);
}

function makeData(data, subKey) {
  let low = 0;
  let high = 0;
  const tempHigh = data.high;
  for (let i = 0; i < 48; ++i) {
    const mask = DES_BITMAP[DES_EXPANSION[i] - 1];
    if (i >= 24) {
      if (mask & tempHigh) high = uint32(high | DES_BITMAP[i - 24]);
    } else if (mask & tempHigh) {
      low = uint32(low | DES_BITMAP[i]);
    }
  }
  low = uint32(low ^ subKey.low);
  high = uint32(high ^ subKey.high);
  const buffer = Buffer.from([
    (low >>> 26) & 0x3f,
    (low >>> 20) & 0x3f,
    (low >>> 14) & 0x3f,
    (low >>> 8) & 0x3f,
    (high >>> 26) & 0x3f,
    (high >>> 20) & 0x3f,
    (high >>> 14) & 0x3f,
    (high >>> 8) & 0x3f,
  ]);
  data.high = 0;
  let byteIndex = 0;
  for (let i = 0; i < 448; i += 64, ++byteIndex) {
    data.high = uint32(data.high | DES_SBOX[buffer[byteIndex] + i]) * 16;
  }
  data.high = uint32(data.high | DES_SBOX[64 * byteIndex + buffer[byteIndex]]);
  let tmp = 0;
  for (let i = 0; i < 32; ++i) {
    if (data.high & DES_BITMAP[DES_PBOX[i] - 1])
      tmp = uint32(tmp | DES_BITMAP[i]);
  }
  data.high = uint32(tmp ^ data.low);
  data.low = tempHigh;
}

function handleData(type, data) {
  let maskOk;
  let low = 0;
  let high = 0;
  for (let i = 0; i < 64; ++i) {
    const v5 = DES_INITIAL[i];
    maskOk = uint32(DES_BITMAP[v5 - 1] & (v5 <= 32 ? data.low : data.high));
    if (!maskOk) continue;
    if (i >= 32) high = uint32(high | DES_BITMAP[i]);
    else low = uint32(low | DES_BITMAP[i]);
  }
  data.low = low;
  data.high = high;

  // 16 轮迭代
  if (type === DesType.Encode) {
    for (let i = 0; i < 16; ++i) makeData(data, subKeys[i]);
  } else {
    for (let i = 15; i >= 0; --i) makeData(data, subKeys[i]);
  }

  const tmp = data.low;
  data.low = data.high;
  data.high = tmp;
  low = 0;
  high = 0;
  for (let i = 0; i < 64; ++i) {
    const v5 = DES_FINAL[i];
    maskOk = uint32(DES_BITMAP[v5 - 1] & (v5 <= 32 ? data.low : data.high));
    if (!maskOk) continue;
    if (i >= 32) high = uint32(high | DES_BITMAP[i]);
    else low = uint32(low | DES_BITMAP[i]);
  }
  data.low = low;
  data.high = high;
}

/**
 * 原地加解密，结果写回 src。
 *
 * @param {Buffer} src 长度必须是 8 的倍数
 * @param {Buffer} key
 * @param {number} type DesType.Encode / DesType.Decode
 */
export function des(src, key, type) {
  makeFirstKey(key);
  for (let i = 0; i < src.byteLength; i += 8) {
    const data = { low: src.readUInt32LE(i), high: src.readUInt32LE(i + 4) };
    handleData(type, data);
    src.writeUInt32LE(data.low, i);
    src.writeUInt32LE(data.high, i + 4);
  }
}
